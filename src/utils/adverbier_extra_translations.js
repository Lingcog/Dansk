const DA_TO_ID = {};
for (const [id, daText] of Object.entries(ID_TO_DA)) {
  DA_TO_ID[daText] = id;
}

const ALL_GROUPS = [
  ADV_P1_G1, ADV_P1_G2, ADV_P1_G3, ADV_P1_G4,
  ADV_P2_G1, ADV_P2_G2, ADV_P2_G3, ADV_P2_G4
];

const MERGED_BY_LANG = {};
for (const group of ALL_GROUPS) {
  if (!group) continue;
  for (const [lang, dict] of Object.entries(group)) {
    if (!MERGED_BY_LANG[lang]) MERGED_BY_LANG[lang] = {};
    Object.assign(MERGED_BY_LANG[lang], dict);
  }
}

export function tAdv(keyOrText, fallbackId = '', lang = getLang()) {
  if (!lang || lang === 'da' || (!keyOrText && !fallbackId)) return '';
  const langDict = MERGED_BY_LANG[lang];
  if (!langDict) return '';
  const id = DA_TO_ID[keyOrText] || keyOrText;
  return langDict[id] || langDict[keyOrText] || (fallbackId ? langDict[fallbackId] : '') || '';
}

export function advTransBlock(keyOrText, fallbackId = '', extraStyle = '') {
  const tr = tAdv(keyOrText, fallbackId);
  if (!tr) return '';
  return `<div class="adv-inline-trans" style="font-size: 0.92rem; color: #94a3b8; font-style: italic; margin-top: 0.3rem; font-weight: 500; line-height: 1.45; ${extraStyle}">${tr}</div>`;
}

export function advTransSpan(keyOrText, fallbackId = '', extraStyle = '') {
  const tr = tAdv(keyOrText, fallbackId);
  if (!tr) return '';
  return `<span class="adv-inline-trans-span" style="font-size: 0.88em; color: #cbd5e1; font-style: italic; margin-left: 0.45rem; font-weight: 500; ${extraStyle}">(${tr})</span>`;
}
