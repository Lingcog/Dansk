const DA_TO_ID = {};
for (const [id, daText] of Object.entries(ID_TO_DA)) {
  if (daText && typeof daText === 'string') {
    DA_TO_ID[daText.trim()] = id;
  }
}

const ALL_GROUPS = [KONJ_G1, KONJ_G2, KONJ_G3, KONJ_G4];

const MERGED_BY_LANG = {};
for (const group of ALL_GROUPS) {
  if (!group) continue;
  for (const [lang, dict] of Object.entries(group)) {
    if (!MERGED_BY_LANG[lang]) MERGED_BY_LANG[lang] = {};
    Object.assign(MERGED_BY_LANG[lang], dict);
  }
}

function getCurrentLangSafe() {
  try {
    if (typeof window !== "undefined") return getLang();
  } catch (e) {}
  return "da";
}

export function tKonj(keyOrText, fallbackId = "", lang = getCurrentLangSafe()) {
  if (!lang || lang === 'da' || (!keyOrText && !fallbackId)) return '';
  const langDict = MERGED_BY_LANG[lang];
  if (!langDict) return '';
  
  const trimmed = typeof keyOrText === 'string' ? keyOrText.trim() : '';
  const id = DA_TO_ID[trimmed] || (ID_TO_DA[keyOrText] ? keyOrText : (DA_TO_ID[keyOrText] || keyOrText));
  
  return langDict[id] || langDict[keyOrText] || (fallbackId ? langDict[fallbackId] : '') || '';
}

export function konjTransBlock(keyOrText, fallbackId = '', extraStyle = '') {
  const tr = tKonj(keyOrText, fallbackId);
  if (!tr) return '';
  return `<div class="konj-inline-trans" style="font-size: 0.92rem; color: #94a3b8; font-style: italic; margin-top: 0.35rem; font-weight: 500; line-height: 1.45; ${extraStyle}">${tr}</div>`;
}

export function konjTransSpan(keyOrText, fallbackId = '', extraStyle = '') {
  const tr = tKonj(keyOrText, fallbackId);
  if (!tr) return '';
  return `<span class="konj-inline-trans-span" style="font-size: 0.88em; color: #cbd5e1; font-style: italic; margin-left: 0.45rem; font-weight: 500; ${extraStyle}">(${tr})</span>`;
}
